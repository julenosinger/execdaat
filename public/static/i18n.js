// ── State ──────────────────────────────────────────────────
let currentLang = localStorage.getItem('arc_lang') || 'en';

// ── Core translation function ─────────────────────────────
function t(key, ...args) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS['en'];
  let val = dict[key] ?? TRANSLATIONS['en'][key] ?? key;
  // Simple interpolation: t('hello_name', 'World') → replaces {0}
  args.forEach((a, i) => { val = val.replace(`{${i}}`, a); });
  return val;
}

// ── Apply translations to DOM ─────────────────────────────
function applyTranslations() {
  // data-i18n="key"  → sets textContent
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });

  // data-i18n-html="key"  → sets innerHTML (for keys with HTML)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    el.innerHTML = t(key);
  });

  // data-i18n-placeholder="key"  → sets placeholder attribute
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });

  // data-i18n-title="key"  → sets title attribute
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key);
  });

  // Update <html lang>
  document.documentElement.lang = currentLang;

  // Update <title>
  document.title = `${t('app_name')} — ${t('app_subtitle')}`;

  // Update lang selector active state
  document.querySelectorAll('.lang-option').forEach(btn => {
    const l = btn.dataset.lang;
    if (l === currentLang) {
      btn.classList.add('bg-purple-700/50', 'text-white', 'border-purple-500');
      btn.classList.remove('text-gray-400', 'border-transparent');
    } else {
      btn.classList.remove('bg-purple-700/50', 'text-white', 'border-purple-500');
      btn.classList.add('text-gray-400', 'border-transparent');
    }
  });
}

// ── Change language ───────────────────────────────────────
function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem('arc_lang', lang);
  applyTranslations();
  // Re-render dynamic content
  if (typeof loadDashboard === 'function' && document.getElementById('tab-content-dashboard') &&
      !document.getElementById('tab-content-dashboard').classList.contains('hidden')) {
    loadDashboard();
  }
  // Update dropdown label
  const toggle = document.getElementById('lang-toggle-label');
  if (toggle) {
    const meta = LANG_META[lang];
    toggle.innerHTML = `${meta.flag} ${meta.label} <i class="fas fa-chevron-down text-xs ml-1 text-gray-500"></i>`;
  }
  // Close dropdown
  const dropdown = document.getElementById('lang-dropdown');
  if (dropdown) dropdown.classList.add('hidden');
}

// ── Toggle dropdown ───────────────────────────────────────
function toggleLangDropdown() {
  const dd = document.getElementById('lang-dropdown');
  if (dd) dd.classList.toggle('hidden');
}

// Close dropdown on outside click
document.addEventListener('click', (e) => {
  if (!e.target.closest('#lang-selector')) {
    const dd = document.getElementById('lang-dropdown');
    if (dd) dd.classList.add('hidden');
  }
});

// ── Init on DOM ready ─────────────────────────────────────
document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
  // Init toggle label
  const toggle = document.getElementById('lang-toggle-label');
  if (toggle) {
    const meta = LANG_META[currentLang];
    toggle.innerHTML = `${meta.flag} ${meta.label} <i class="fas fa-chevron-down text-xs ml-1 text-gray-500"></i>`;
  }
});
